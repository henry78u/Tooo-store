// Helper to construct variants
function makeVariants(productId: string, sizes: string[], colours: { name: string }[], defaultStock = 12) {
  const variants = [];
  for (const c of colours) {
    for (const s of sizes) {
      variants.push({
        variantId: `${productId}-${c.name.toLowerCase().replace(/\s+/g, '-')}-${s.toLowerCase()}`,
        size: s,
        colour: c.name,
        stock: s === 'XXL' ? 2 : defaultStock,
        sku: `TOOO-${productId.toUpperCase()}-${s}-${c.name.slice(0, 3).toUpperCase()}`,
      });
    }
  }
  return variants;
}

